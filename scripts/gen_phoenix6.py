"""
Generate the Phoenix 6 C API of the RP2040 bridge client from schema.json.

    # Optional: refresh schema.json from the installed phoenix6 package
    python3 scripts/gen_phoenix6.py --from-installed

    # Regenerate the C files from the committed schema.json
    python3 scripts/gen_phoenix6.py

Outputs:
    include/canbus_rp2040/phoenix6_generated.h
    lib/phoenix6/phoenix6_generated.c
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HOST = ROOT / "host" / "phoenix6_bridge"
sys.path.insert(0, str(HOST))

from phoenix6_bridge import schema as schema_mod  # noqa: E402

HEADER = ROOT / "include" / "canbus_rp2040" / "phoenix6_generated.h"
SOURCE = ROOT / "lib" / "phoenix6" / "phoenix6_generated.c"

C_TYPES = {"float": "double", "bool": "bool", "int": "int32_t", "enum": "int32_t"}
TYPE_CODES = {
    "float": "PHOENIX6_TYPE_FLOAT",
    "bool": "PHOENIX6_TYPE_BOOL",
    "int": "PHOENIX6_TYPE_INT",
    "enum": "PHOENIX6_TYPE_ENUM",
    "control": "PHOENIX6_TYPE_CONTROL",
}


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name)
    return s.lower()


def enum_prefix(enum_name: str) -> str:
    base = enum_name[:-5] if enum_name.endswith("Value") else enum_name
    return "PHOENIX6_" + snake(base).upper()


def c_default(p: dict) -> str:
    t = p["type"]
    d = p["default"]
    if t == "bool":
        return "true" if d else "false"
    if t in ("int", "enum"):
        return str(int(d))
    return repr(float(d))


def generate(schema: dict) -> tuple[str, str]:
    enums = schema["enums"]
    enum_index = {name: i for i, name in enumerate(enums)}
    controls = schema["controls"]
    by_name = {c["name"]: c for c in controls}
    h = []
    c = []
    version = schema["phoenix6_version"]
    sh = schema_mod.schema_hash(schema)

    banner = (
        "/*\n"
        " * Copyright (c) 2026 CANBusRP2040 contributors\n"
        " *\n"
        " * SPDX-License-Identifier: Apache-2.0\n"
        " *\n"
        f" * GENERATED by scripts/gen_phoenix6.py from schema.json (Phoenix 6 {version}).\n"
        " * Do not edit.\n"
        " */\n"
    )

    h.append(banner)
    h.append("#ifndef CANBUS_RP2040_INCLUDE_PHOENIX6_GENERATED_H_")
    h.append("#define CANBUS_RP2040_INCLUDE_PHOENIX6_GENERATED_H_\n")
    h.append("#include <stdbool.h>\n#include <stdint.h>\n")
    h.append('#ifdef __cplusplus\nextern "C" {\n#endif\n')
    h.append(f'/** Phoenix 6 version the API was generated from. */')
    h.append(f'#define PHOENIX6_GENERATED_VERSION "{version}"')
    h.append("/** Hash of the wire schema, checked against the host bridge. */")
    h.append(f"#define PHOENIX6_SCHEMA_HASH 0x{sh:08x}U\n")

    # Enums
    h.append("/* Enumerations (values as defined by Phoenix 6) */\n")
    for name, members in enums.items():
        prefix = enum_prefix(name)
        h.append(f"/** Phoenix 6 {name}. */")
        h.append(f"enum phoenix6_{snake(name[:-5] if name.endswith('Value') else name)} {{")
        for m, v in members.items():
            h.append(f"\t{prefix}_{m} = {v},")
        h.append("};\n")

    # Control IDs
    h.append("/** Control request identifiers. */")
    h.append("enum phoenix6_control_id {")
    h.append("\tPHOENIX6_CONTROL_ID_NONE = 0,")
    for ctl in controls:
        h.append(f"\tPHOENIX6_CONTROL_ID_{snake(ctl['name']).upper()} = {ctl['id']},")
    h.append(f"\tPHOENIX6_CONTROL_ID_COUNT = {len(controls) + 1},")
    h.append("};\n")

    # Parameter structs
    for ctl in controls:
        sname = snake(ctl["name"])
        notes = []
        if ctl["requires_canivore"]:
            notes.append("Requires Phoenix Pro and a CANivore (CAN FD).")
        elif ctl["requires_pro"]:
            notes.append("Requires Phoenix Pro.")
        h.append(f"/** Parameters of the Phoenix 6 {ctl['name']} control request."
                 + (f" {notes[0]}" if notes else "") + " */")
        h.append(f"struct phoenix6_{sname} {{")
        if not ctl["params"]:
            h.append("\t/** No parameters. */")
            h.append("\tuint8_t unused;")
        for p in ctl["params"]:
            if p["type"] == "control":
                h.append(f"\t/** {p['control']} request. */")
                h.append(f"\tstruct phoenix6_{snake(p['control'])} {p['name']};")
                continue
            doc = []
            if "unit" in p:
                doc.append(f"unit: {p['unit']}")
            if "enum" in p:
                doc.append(f"enum phoenix6_{snake(p['enum'][:-5])}")
            if "default" in p:
                doc.append(f"default {c_default(p)}")
            else:
                doc.append("required")
            h.append(f"\t/** {p['name']} ({', '.join(doc)}) */")
            h.append(f"\t{C_TYPES[p['type']]} {p['name']};")
        h.append("};\n")

    # Control container
    h.append("/** A Phoenix 6 control request for a Talon FX. */")
    h.append("struct phoenix6_control {")
    h.append("\t/** Request type. */")
    h.append("\tenum phoenix6_control_id id;")
    h.append("\t/** Rate at which Phoenix 6 resends the request (0: send once). */")
    h.append("\tdouble update_freq_hz;")
    h.append("\t/** Request parameters, selected by @a id. */")
    h.append("\tunion {")
    for ctl in controls:
        sname = snake(ctl["name"])
        h.append(f"\t\tstruct phoenix6_{sname} {sname};")
    h.append("\t};")
    h.append("};\n")
    first = snake(controls[0]["name"])
    h.append("/** Offset of the parameter union within struct phoenix6_control. */")
    h.append(f"#define PHOENIX6_CONTROL_PARAMS_OFFSET offsetof(struct phoenix6_control, {first})\n")

    # Initializer macros
    h.append("/*")
    h.append(" * Initializers with the Phoenix 6 defaults. NAME_PARAMS(required...) gives the")
    h.append(" * parameter struct, NAME(required...) a complete struct phoenix6_control.")
    h.append(" */\n")
    for ctl in controls:
        sname = snake(ctl["name"])
        upper = sname.upper()
        required = [p for p in ctl["params"] if p["type"] == "control" or "default" not in p]
        args = ", ".join(f"{p['name']}_" for p in required)
        inits = []
        for p in ctl["params"]:
            if p["type"] == "control" or "default" not in p:
                inits.append(f".{p['name']} = ({p['name']}_)")
            else:
                inits.append(f".{p['name']} = {c_default(p)}")
        if not inits:
            inits = [".unused = 0"]
        h.append(f"#define PHOENIX6_{upper}_PARAMS({args}) \\")
        h.append(f"\t((struct phoenix6_{sname}){{{', '.join(inits)}}})")
        h.append(f"#define PHOENIX6_{upper}({args}) \\")
        h.append(f"\t((struct phoenix6_control){{.id = PHOENIX6_CONTROL_ID_{upper}, \\")
        h.append(f"\t\t.update_freq_hz = {float(ctl['update_freq_hz'] or 0.0)!r}, \\")
        h.append(f"\t\t.{sname} = PHOENIX6_{upper}_PARAMS({args})}})")
        h.append("")

    # Config fields
    h.append("/** Talon FX configuration fields (group.field). */")
    h.append("enum phoenix6_config_field {")
    h.append("\tPHOENIX6_CONFIG_NONE = 0,")
    for f in schema["configs"]:
        h.append(f"\tPHOENIX6_CONFIG_{f['group'].upper()}_{f['field'].upper()} = {f['id']},")
    h.append(f"\tPHOENIX6_CONFIG_COUNT = {len(schema['configs']) + 1},")
    h.append("};\n")

    # Signals
    h.append("/** Talon FX status signals. */")
    h.append("enum phoenix6_signal {")
    h.append("\tPHOENIX6_SIGNAL_NONE = 0,")
    for s in schema["signals"]:
        h.append(f"\tPHOENIX6_SIGNAL_{s['name'].upper()} = {s['id']},")
    h.append(f"\tPHOENIX6_SIGNAL_COUNT = {len(schema['signals']) + 1},")
    h.append("};\n")

    h.append("#ifdef __cplusplus\n}\n#endif\n")
    h.append("#endif /* CANBUS_RP2040_INCLUDE_PHOENIX6_GENERATED_H_ */")

    # ---- Source: descriptor tables ----
    c.append(banner)
    c.append("#include <stddef.h>\n")
    c.append("#include <canbus_rp2040/phoenix6.h>\n")

    for name, members in enums.items():
        c.append(f"static const struct phoenix6_enum_member enum_{snake(name)}[] = {{")
        for m, v in members.items():
            c.append(f'\t{{"{m}", {v}}},')
        c.append("};\n")
    c.append("const struct phoenix6_enum_desc phoenix6_enum_descs[] = {")
    for name, members in enums.items():
        c.append(f'\t{{"{name}", ARRAY_SIZE(enum_{snake(name)}), enum_{snake(name)}}},')
    c.append("};\n")
    c.append("const size_t phoenix6_enum_count = ARRAY_SIZE(phoenix6_enum_descs);\n")

    for ctl in controls:
        sname = snake(ctl["name"])
        if not ctl["params"]:
            continue
        c.append(f"static const struct phoenix6_param_desc params_{sname}[] = {{")
        for p in ctl["params"]:
            off = f"offsetof(struct phoenix6_{sname}, {p['name']})"
            if p["type"] == "control":
                sub = by_name[p["control"]]["id"]
                c.append(f'\t{{"{p["name"]}", {off}, PHOENIX6_TYPE_CONTROL, 0xFF, {sub}, '
                         f"true, 0.0}},")
            else:
                ei = enum_index[p["enum"]] if "enum" in p else 0xFF
                required = "default" not in p
                default = 0.0 if required else float(p["default"])
                c.append(f'\t{{"{p["name"]}", {off}, {TYPE_CODES[p["type"]]}, {ei}, 0, '
                         f"{'true' if required else 'false'}, {default!r}}},")
        c.append("};\n")

    c.append("const struct phoenix6_control_desc phoenix6_control_descs[] = {")
    for ctl in controls:
        sname = snake(ctl["name"])
        flags = []
        if ctl["requires_pro"]:
            flags.append("PHOENIX6_CONTROL_FLAG_PRO")
        if ctl["requires_canivore"]:
            flags.append("PHOENIX6_CONTROL_FLAG_CANIVORE")
        params = f"params_{sname}" if ctl["params"] else "NULL"
        c.append(
            f'\t[{ctl["id"] - 1}] = {{"{ctl["name"]}", {ctl["id"]}, '
            f"sizeof(struct phoenix6_{sname}), {int(ctl['update_freq_hz'] or 0)}, "
            f"{len(ctl['params'])}, {' | '.join(flags) or '0'}, {params}}},"
        )
    c.append("};\n")

    c.append("const struct phoenix6_config_desc phoenix6_config_descs[] = {")
    for f in schema["configs"]:
        ei = enum_index[f["enum"]] if "enum" in f else 0xFF
        c.append(
            f'\t[{f["id"] - 1}] = {{"{f["group"]}", "{f["field"]}", {f["id"]}, '
            f"{TYPE_CODES[f['type']]}, {ei}}},"
        )
    c.append("};\n")

    c.append("const struct phoenix6_signal_desc phoenix6_signal_descs[] = {")
    for s in schema["signals"]:
        ei = enum_index[s["enum"]] if "enum" in s else 0xFF
        unit = f'"{s["unit"]}"' if "unit" in s else "NULL"
        c.append(
            f'\t[{s["id"] - 1}] = {{"{s["name"]}", {unit}, {s["id"]}, '
            f"{TYPE_CODES[s['type']]}, {ei}}},"
        )
    c.append("};")

    return "\n".join(h) + "\n", "\n".join(c) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--from-installed", action="store_true",
                        help="regenerate schema.json from the installed phoenix6 package first")
    parser.add_argument("--check", action="store_true",
                        help="fail if the generated files are out of date")
    args = parser.parse_args()

    if args.from_installed:
        schema = schema_mod.build_schema()
        schema_mod.SCHEMA_PATH.write_text(json.dumps(schema, indent=1) + "\n", encoding="utf-8")
    schema = schema_mod.load_schema()

    header, source = generate(schema)
    if args.check:
        stale = [p for p, text in ((HEADER, header), (SOURCE, source))
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            sys.exit("out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        return

    HEADER.write_text(header, encoding="utf-8")
    SOURCE.parent.mkdir(parents=True, exist_ok=True)
    SOURCE.write_text(source, encoding="utf-8")
    print(f"generated {HEADER.relative_to(ROOT)} and {SOURCE.relative_to(ROOT)} "
          f"(Phoenix 6 {schema['phoenix6_version']}, hash 0x{schema_mod.schema_hash(schema):08x})")


if __name__ == "__main__":
    main()
